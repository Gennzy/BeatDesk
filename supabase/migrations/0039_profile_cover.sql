-- 0039. Обложка профиля ----------------------------------------------
--
-- У бита есть обложка, у профиля — нет. Профиль без обложки выглядит как
-- служебная страница: человек видит ник и счётчики, но не витрину.
-- Обложка — это то, что делает профиль узнаваемым с первого взгляда, и
-- BeatChain без неё не обходится.
--
-- Отдельное поле, а не переиспользование чего-то: аватар у профиля один и
-- круглый, обложка широкая, и склеивать их в одну картинку нельзя.

alter table public.profiles
  add column if not exists cover_url text;

comment on column public.profiles.cover_url is
  'Широкая обложка профиля. NULL — профиль без обложки, шапка остаётся компактной';

-- Загрузка идёт в тот же бакет covers, что и обложки битов: отдельный
-- бакет ради одной сущности означал бы вторую политику доступа и вторую
-- папку, которую надо помнить при уборке.
create index if not exists profiles_cover_idx on public.profiles (id)
  where cover_url is not null;