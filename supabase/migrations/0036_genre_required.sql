-- 0036. Жанр обязателен ----------------------------------------------
--
-- Миграция 0030 завела колонку genre, таблицу жанров и подсчёт битов, но
-- писать жанр было некому: пустая форма без жанра создавала бит с genre =
-- null. Дальше фильтр по жанру показывал ноль битов и выглядел как
-- «жанров на площадке нет».
--
-- Теперь жанр обязателен, и это закреплено на трёх уровнях, потому что
-- каждое из них ловит своё:
--
--   форма     — не даёт отправить пустое
--   сервер    — не даёт обойти форму
--   база      — не даёт обойти сервер
--
-- Одного достаточно для удобства, но недостаточно: форму можно забыть, а
-- сервер — вызвать напрямую. Колонка NOT NULL закрывает и то, и другое.

-- 1. Что делать с уже выложенными битами -----------------------------
--
-- Обязательный жанр нельзя ввести, не ответив на вопрос «а что с теми,
-- кто выложился раньше». Отвечаем честно: проставляем «Другое».
--
-- Вариант удалить такие биты отклонён намеренно. «Другое» — это правда:
-- жанр действительно не назван, и покупатель видит честную категорию,
-- а не бит, исчезнувший с витрины без объяснения.

update public.beats set genre = 'other' where genre is null;

-- 2. Обязательность ---------------------------------------------------

alter table public.beats
  alter column genre set default 'other';

alter table public.beats
  alter column genre set not null;

comment on column public.beats.genre is
  'Жанр из закрытого списка. Обязателен: без него бит не попадает ни в один фильтр и выглядит как потерянный';

alter table public.beats
  drop constraint if exists beats_genre_required;

alter table public.beats
  add constraint beats_genre_required check (btrim(genre) <> '');

-- 3. Почему список жанров не продублирован в CHECK --------------------
--
-- Набор значений (trap, opium и прочие двенадцать) проверяет сервер: он
-- сверяется со списком из кода, который совпадает с таблицей genres.
-- Дублировать его здесь значило бы завести третью копию одного списка и
-- подписаться на расхождение, которое заметят покупатели.
--
-- CHECK выше ловит только пустую строку — то, что сервер пропустить не
-- может, а список отдан на ответственность кода.

-- 4. Фильтр по жанру больше не может вернуть пустоту незаметно ---------
--
-- Индекс уже был в 0030 на саму колонку. Здесь важнее другое: раньше
-- genre = null молча выпадал из любого подсчёта, и «Другое» с нулём битов
-- выглядело как ошибка данных. Теперь пустых жанров не остаётся вовсе.

create index if not exists beats_genre_required_idx on public.beats (genre)
  where genre is not null;