-- Счётчики просмотров и прослушиваний больше не вызываются напрямую.
--
-- Применяется после 0057.
--
-- ---------------------------------------------------------------------------
-- ЧТО БЫЛО
--
-- increment_plays и bump_beat_counter были выданы и anon, и authenticated:
-- гость тоже слушает бит и открывает страницу, и без гостя счётчики не
-- считали бы ничего. Намерение было правильное, а исполнение — нет.
--
-- Обе функции вызываются из маршрутов, и в маршрутах стоит ограничение: двадцать
-- прослушиваний и сто двадцать просмотров в минуту на клиента. Но сама функция
-- была доступна и через PostgREST напрямую — а там ограничения нет. Скрипт
-- мог крутить счётчик прослушиваний без предела.
--
-- Счётчик прослушиваний входит в рейтинг ленты (beat_score), то есть это был
-- способ поднять свой бит в выдаче.
--
-- ---------------------------------------------------------------------------
-- КАК СДЕЛАНО
--
-- Счётчики теперь считает служебный клиент приложения: маршрут остаётся
-- единственным путём, а значит и его ограничение — единственным, что
-- действует.
--
-- Гостю это ничего не ломает: гость по-прежнему слушает бит и открывает
-- страницу, счётчики считаются те же самые. Меняется только то, кто именно
-- дёргает функцию.

revoke execute on function public.increment_plays(uuid) from public;
revoke execute on function public.bump_beat_counter(uuid, text) from public;

grant execute on function public.increment_plays(uuid) to service_role;
grant execute on function public.bump_beat_counter(uuid, text) to service_role;

comment on function public.increment_plays is
  'Увеличивает счётчик прослушиваний бита. Вызывается только маршрутом /api/beats/[id]/play через служебный клиент: раньше функция была доступна анонимам напрямую через PostgREST, минуя ограничение маршрута, а счётчик входит в рейтинг ленты.';
