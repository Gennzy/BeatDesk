-- BeatDesk: алиасы/сценические имена битмейкера
--
-- Битмейкер может выступать под несколькими именами (продюсерский ник,
-- артистический псевдоним, имя для Type Beat). Хранятся как массив строк,
-- чтобы позже можно было привязать к каждому алиасу отдельный профиль
-- (roster management), не ломая текущую схему.

alter table public.profiles
  add column if not exists aliases text[] not null default '{}'::text[];