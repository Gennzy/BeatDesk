-- Рейтинг ленты перестал стареть.
--
-- Применяется после 0054.
--
-- ---------------------------------------------------------------------------
-- ЧТО БЫЛО СЛОМАНО
--
-- Лента по умолчанию сортируется по beats.score, а формула внутри score
-- содержит затухание по времени: бит без реакций через три дня весит вдвое
-- меньше, чем в первый. Значит score обязан пересчитываться, и пересчитываться
-- постоянно.
--
-- Пересчитывал только триггер на реакциях. Ставил лайк — пересчитался; прошло
-- два дня без реакций — score остался прежним. Новый бит без реакций навсегда
-- оставался с нулём, а бит с лайком полугодовой давности стоял по весу того дня.
--
-- Функция recount_all_beats() в проекте была, права ей даны были, и её не
-- звал никто. Колонка scored_at — «когда последний пересчёт» — не читалась и не
-- писалась нигде: механизм, который для этого и создавался, был наполовину
-- готов.
--
-- ---------------------------------------------------------------------------
-- ПОЧЕМУ ПЕРЕСЧЁТ ПРИ ЧТЕНИИ, А НЕ ПО РАСПИСАНИЮ
--
-- Расписание требует внешнего планировщика и настройки на стороне хостинга.
-- Пока его нет, score стареет тем быстрее, чем реже открывают ленту, — а
-- деградацию нельзя чинить только там, где её заметили.
--
-- Пересчёт при чтении делается один раз на всю страницу и только для тех
-- битов, чей score старше десяти минут. Обычный запрос ленты не трогает
-- ничего: условие отсекает всё свежее, а индекс по scored_at отвечает за
-- скорость. Зато рейтинг перестаёт быть замороженным без всякой внешней
-- настройки — правило «пересчитать, если устарело» не может забыть выполниться.
--
-- Отзыв отдавать нельзя: это запись в таблицу beats для всех, и роль с правом
-- вызова смогла бы запустить полный пересчёт хоть сотню раз в секунду.

create or replace function public.refresh_beat_scores(p_max_age_seconds integer default 600)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  v_count integer;
begin
  /*
   * Порог снизу ограничен: ноль превращал бы в «пересчитать всё, что хоть
   * раз трогнули», а отрицательное значение — в пересчёт каждой строки на
   * каждом открытии ленты.
   */
  update public.beats b
     set score = public.beat_score(b.id),
         scored_at = now(),
         updated_at = b.updated_at
   where b.scored_at is null
      or b.scored_at < now() - make_interval(secs => greatest(coalesce(p_max_age_seconds, 600), 60));

  get diagnostics v_count = row_count;

  return v_count;
end;
$$;

grant execute on function public.refresh_beat_scores(integer) to anon, authenticated;

comment on function public.refresh_beat_scores is
  'Пересчитывает вес битов, у которых он старше указанного числа секунд. Возвращает число обновлённых строк: если их ноль, запрос ленты не сделал лишней работы.';