/**
 * Требования BeatDesk к биту, который выставлен на продажу.
 *
 * Раньше здесь лежали требования чужих маркетплейсов: BeatStars, Airbit,
 * BeatChain. Проверять было нечего — правила принадлежали не нам, а
 * площадкам, и половина из них никогда не была опубликована.
 *
 * Теперь площадка одна, и она наша, поэтому требования мы не снимаем
 * с чужой формы, а задаём сами. Это политика продукта, а не факт о
 * третьем лице: если цифра кажется неудобной, она меняется здесь.
 *
 * Правило помечено статусом доверия, и это не формальность:
 *
 * - `documented` — наше требование, оно объявлено в справке BeatDesk;
 * - `observed`   — выведено из того, что мы уже отдаём покупателям;
 * - `unknown`    — требование не решено, и проверка молчит вместо того,
 *                  чтобы выдумать число.
 *
 * Выдуманное правило опаснее отсутствующего: битмейкер поверит чекбоксу,
 * выставит уровень, который мы не сможем отдать, и покупатель получит
 * заказ без файла.
 *
 * Отдельная ось — уровень лицензии. Требования к MP3 и к архиву со
 * стемами разные, и уровень, который стоит денег, но не обеспечен файлом,
 * — это не «неаккуратно», это невыполнимый заказ.
 */

import { MAX_ASSET_BYTES } from "@/lib/beats";

/** Статус доверия к требованию. */
export type Trust = "documented" | "observed" | "unknown";

/**
 * Уровни лицензии — те же ключи, что и в `prices`.
 *
 * `bundle` в названии исторический: в нём лежит уровень WAV.
 */
export type TierId = "mp3" | "bundle" | "trackout" | "exclusive";

export type FieldKind = "wav" | "mp3" | "stems" | "artwork" | "tags";

export type Check = {
  /** Что проверяем, по-человечески. */
  label: string;
  /** Поле файла, к которому относится правило. */
  field: FieldKind;
  /** Что именно нужно. */
  requirement: string;
  trust: Trust;
  /** Раздел справки BeatDesk. */
  source?: string;
};

export type FieldRule = {
  /** Минимальная разрядность в битах. */
  minBits?: number;
  maxBits?: number;
  /** Частота дискретизации, Гц. */
  minSampleRate?: number;
  maxSampleRate?: number;
  /** Минимум каналов: мастер без стерео не годится. */
  minChannels?: number;
  /** Потолок размера файла, байт. */
  maxBytes?: number;
  /** Минимальный битрейт MP3, кбит/с. */
  minKbps?: number;
  /** Потолок длительности, секунд. */
  maxSeconds?: number;
  /** Обложка: квадратная сторона. */
  artworkSide?: number;
  /** Минимальная сторона обложки в пикселях. */
  artworkMinSide?: number;
  trust: Trust;
};

export type TierRules = {
  id: TierId;
  label: string;
  /** Подпись в интерфейсе: что покупатель получит. */
  delivers: string;
  /**
   * Что обязано лежать в бите, чтобы этот уровень можно было продать.
   *
   * Пустой уровень мы показываем в карточке, но продавать не даём:
   * покупатель не должен узнать об отсутствии файла после оплаты.
   */
  requires: { wav?: boolean; mp3?: boolean; stems?: boolean };
  /** Нужен ли мастер, который отдаётся покупателю целиком. */
  master: boolean;
  checks: Check[];
  /** Замечания, которые не выразить числом. */
  notes: string[];
};

const MB = 1024 * 1024;

/**
 * Формат полей — общий для всех уровней.
 *
 * Различается только то, что реально различается: стемы требуем в 24 бит,
 * потому что покупатель их сводит и слышит каждое квантование, а превью
 * оставляем в 16 бит, потому что оно звучит в браузере, а не в DAW.
 */
const FIELDS: Record<FieldKind, FieldRule> = {
  wav: {
    minBits: 16,
    maxBits: 32,
    minSampleRate: 44100,
    maxSampleRate: 48000,
    minChannels: 2,
    /**
     * Потолок мастера берём из загрузчика, а не задаём здесь вторым числом.
     *
     * Раньше правила говорили 300 МБ, а загрузчик пропускал 500, и человек
     * загружал файл, который проходил предыдущую проверку и падал уже в
     * момент отправки. Две правды об одном потолке — это всегда расхождение.
     *
     * 500 МБ умещаются даже на бесплатном тарифе: мастер режется на куски по
     * 20 МБ, и ограничение Supabase в 50 МБ на объект до этих кусков не
     * относится. На платных тарифах бакет больше, и потолок можно поднять —
     * см. MAX_ASSET_BYTES в lib/beats.
     */
    maxBytes: MAX_ASSET_BYTES,
    maxSeconds: 600,
    trust: "documented",
  },
  mp3: {
    minBits: 16,
    maxBits: 24,
    minSampleRate: 44100,
    maxSampleRate: 48000,
    minChannels: 2,
    maxBytes: 15 * MB,
    // 320 — это то, ниже чего превью уже звучит грязно на телефоне,
    // а покупатель выбирает бит по превью, не по мастеру.
    minKbps: 320,
    maxSeconds: 600,
    trust: "documented",
  },
  stems: {
    // Стемы — материал для сведения. Каждый шаг квантования в них слышен
    // после сложения голосов, поэтому 16 бит — это приговор.
    minBits: 24,
    minSampleRate: 44100,
    maxSampleRate: 48000,
    minChannels: 2,
    trust: "documented",
  },
  artwork: {
    // Требование к обложке пока не решено: площадка обрежет сама, а
    // нижнюю границу мы не готовы назвать, потому что не знаем, какой
    // размер кадрирования переживёт все наши превью.
    trust: "unknown",
  },
  tags: { trust: "documented" },
};

