/**
 * Поиск бита на музыкальных площадках.
 *
 * ---------------------------------------------------------------------------
 * ЗАЧЕМ ИНТЕРФЕЙС
 *
 * Движок поиска — отдельная часть, которую мы меняем: свой или чужой. Он
 * ходит по площадкам, качает превью и сравнивает звук. Всё остальное — отчёт,
 * журнал, атрибуция — от движка не зависит.
 *
 * Поэтому сканер описан здесь, а не в коде площадок: подмена движка не должна
 * трогать ни отчёт, ни сверку с нашими покупателями.
 *
 * ---------------------------------------------------------------------------
-- ---------------------------------------------------------------------------
 * ЧТО ДОЛЖЕН ВОЗВРАЩАТЬ СКАНЕР
 *
 * Находку с процентом совпадения и — если движок умеет — отпечатком
 * совпавшего файла. Отпечаток нужен, чтобы сопоставить находку с нашим
 * журналом скачиваний: без него отчёт скажет «где-то use», а с ним — «вот
 * кто именно у нас брал».
 */

/** Площадка, на которой нашли. */
export type ScanPlatform = "spotify" | "apple" | "youtube" | "soundcloud" | "deezer" | "tidal" | "amazon" | "other";

/** Находка: релиз, где звучит бит. */
export type ScanMatch = {
  platform: ScanPlatform;
  /** Идентификатор трека на площадке. */
  externalId: string | null;
  title: string | null;
  artist: string | null;
  releaseDate: string | null;
  label: string | null;
  upc: string | null;
  isrc: string | null;
  /** Процент совпадения, от 0 до 100. */
  confidence: number;
  url: string | null;
  /**
   * Отпечаток совпавшего файла.
   *
   * По нему сверка с журналом скачиваний: он отвечает, чей это релиз. Без
   * него находка остаётся «где-то use», а это половина ценности.
   */
  envelope: string | null;
};

/** Что сканеру отдают. */
export type ScanRequest = {
  beatId: string;
  /** Отпечаток мастера: по нему ищем. */
  envelope: string;
  /** Название бита: ищем по нему кандидатов, а не по всей площадке. */
  title: string;
  /** Артисты бита: нужны для поиска кандидатов. */
  artists: string[];
  /** Сколько площадок обходить. */
  platforms: ScanPlatform[];
};

/** Сканер: одна реализация — один движок. */
export type Scanner = {
  /** Имя движка: видно в отчёте, чтобы было понятно, чем искали. */
  name: string;
  /** Ищет находки по биту. */
  scan: (request: ScanRequest) => Promise<ScanMatch[]>;
};

/**
 * Сканер-заглушка.
 *
 * Возвращает пусто и говорит почему. Молчащий сканер опаснее отсутствующего:
 * отчёт «находок нет» выглядит как результат проверки, а на деле проверки не
 * было.
 */
export function nullScanner(reason = "движок поиска не подключён"): Scanner {
  return {
    name: "none",
    scan: async () => {
      throw new Error(reason);
    },
  };
}

/**
 * Отбор находок, которым можно верить.
 *
 * Совпадение ниже порога — это не находка, а совпадение. Бит — простая
 * вещь, и половина треков в жанре будет похожа на него по первому
 * сорока секундам.
 */
export const MIN_CONFIDENCE = 70;

/** Оставляет только те находки, которым можно верить. */
export function confidentMatches(matches: ScanMatch[], threshold = MIN_CONFIDENCE): ScanMatch[] {
  return matches.filter((match) => match.confidence >= threshold);
}
