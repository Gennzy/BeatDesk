/**
 * Задачи публикации: статусы и переходы.
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ СОСТОЯНИЕ ЖИВЁТ ЗДЕСЬ, А НЕ В БАЗЕ
 *
 * Статус задачи управляет тем, что человек видит и что ему доступно нажать:
 * появится ли кнопка повтора, можно ли открыть ролик. Проверять это в двух
 * местах — здесь и в SQL — значит через месяц забыть про одну из проверок.
 *
 * Поэтому переходы описаны один раз, а база принимает то, что прислал сервер,
 * и считает попытки сама. Клиент статусы не выдумывает: он их не придумывает,
 * а сообщает, на каком шаге находится.
 *
 * ---------------------------------------------------------------------------
 * ПОЧЕМУ «ОПУБЛИКОВАНО» — ТУПИК
 *
 * В опубликованной задаче лежит video_id, из которого потом считаются
 * просмотры. Возвращать такую задачу в draft нельзя: video_id при этом либо
 * потерялся бы, либо остался бы висеть на задаче, которая на самом деле
 * ничего не публиковала. Оба варианта портят будущую статистику незаметно.
 *
 * Если захотелось нового ролика с другими метаданными — это новая задача из
 * мастера, ровно то, чем мастер и занимается.
 */

/** Куда задача может прийти и где может быть. */
export const JOB_STATUSES = ["draft", "rendering", "uploading", "published", "failed"] as const;

export type JobStatus = (typeof JOB_STATUSES)[number];

/**
 * Переходы.
 *
 * Таблица, а не набор if: правило «куда можно» читается целиком и не
 * размазывается по веткам. Всё, чего здесь нет, — невозможно.
 *
 * Отступление от остального кода намеренное: цепочка в одну строку. Длина
 * строки важнее её читаемости здесь — правило перехода это предложение, и
 * предложение должно помещаться в одну строку, иначе его перестанут читать.
 */
const TRANSITIONS: Record<JobStatus, readonly JobStatus[]> = {
  // Задача создана, ролик ещё не начали собирать.
  draft: ["rendering", "failed"],
  // Браузер рисует ролик. Упасть можно на любом шаге.
  rendering: ["uploading", "failed"],
  // Ролик собран, кучки летят в YouTube.
  uploading: ["published", "failed"],
  // Ролик вышел. Дальше только смотреть статистику.
  published: [],
  // Отказ. Единственный выход — повторить.
  failed: ["draft"],
};

/** Разрешён ли переход. */
export function canTransition(from: JobStatus, to: JobStatus): boolean {
  return TRANSITIONS[from].includes(to);
}

/** Разрешён ли статус вообще: приходит из базы и из тела запроса. */
export function isJobStatus(value: unknown): value is JobStatus {
  return typeof value === "string" && (JOB_STATUSES as readonly string[]).includes(value);
}

/** Задача дошла до конца: ролик вышел, повторять нечего. */
export function isFinal(status: JobStatus): boolean {
  return status === "published";
}

/** Задача сейчас в работе: идёт рендер или загрузка. */
export function isRunning(status: JobStatus): boolean {
  return status === "rendering" || status === "uploading";
}

/**
 * Зависла ли задача.
 *
 * Главная особенность нашей архитектуры: ролик собирает и заливает браузер,
 * а сервер только слушает. Закрыли вкладку посередине — статус навсегда
 * остался «рендерится», и некому его сдвинуть: воркера, который доделает
 * работу без человека, у нас нет и не будет, пока рендер не уедет на сервер.
 *
 * Поэтому зависание — не поломка, а нормальное состояние, и оно обязано быть
 * видно сразу, а не через неделю, когда человек уже забыл про ролик.
 *
 * Порог в 15 минут: ролик собирается в реальном времени, три минуты трека —
 * три минуты сборки, и быстрее он не пойдёт. Загрузка дольше. Полчаса
 * молчания — это точно закрытая вкладка, а не «идёт, но медленно».
 */
export function isStuck(
  job: { status: JobStatus; updatedAt: string },
  staleMinutes = 15,
  now: Date = new Date(),
): boolean {
  if (!isRunning(job.status)) return false;

  const updated = Date.parse(job.updatedAt);

  // Метка времени не разобралась — считаем зависшим, а не рабочим.
  // Наоборот опаснее: человек не увидит кнопку повтора.
  if (!Number.isFinite(updated)) return true;

  return now.getTime() - updated > staleMinutes * 60_000;
}

/**
 * Можно ли повторить.
 *
 * Два случая: явный отказ и зависание. Второе важнее — отказ человек видит
 * сразу, а зависшая задача молча лежит месяц и выглядит как «в работе».
 */
export function canRetry(
  job: { status: JobStatus; updatedAt: string },
  staleMinutes = 15,
  now = new Date(),
): boolean {
  return job.status === "failed" || isStuck(job, staleMinutes, now);
}

/**
 * Тон статуса для интерфейса.
 *
 * Слов только три, и это не недосмотр, а следствие палитры: в проекте есть
 * лаймовый signal, красный danger и серый mute, и отдельного цвета «успех»
 * не существует. Пятёрка оттенков означала бы пять неразличимых оттенков
 * одного тона.
 *
 * Распределение отсюда:
 *
 *   - published — signal: лаймовый в проекте и есть успех, как в тостах;
 *   - работа — mute: она временная, и в статичном списке лаймовый цвет читался
 *     бы как «всё сделано». Различает работа и успех не цвет, а процент
 *     прогресса в строке;
 *   - отказ и зависание — danger: человек должен понять, что ролик не выйдет
 *     сам.
 */
export type JobTone = "mute" | "signal" | "danger";

export function jobTone(
  job: { status: JobStatus; updatedAt: string },
  staleMinutes = 15,
  now = new Date(),
): JobTone {
  if (job.status === "failed") return "danger";

  // Зависание выглядит как опасность, а не как работа: человек должен
  // понимать, что ролик не выйдет, пока он не нажмёт повтор.
  if (isStuck(job, staleMinutes, now)) return "danger";

  if (job.status === "published") return "signal";

  return "mute";
}

/** Список задач, готовых к повтору: то, что человек обязан увидеть первым. */
export function retryableJobs<T extends { status: JobStatus; updatedAt: string }>(
  jobs: T[],
  staleMinutes = 15,
  now = new Date(),
): T[] {
  return jobs.filter((job) => canRetry(job, staleMinutes, now));
}

/**
 * Что показать в строке истории вместо идентификатора.
 *
 * Задача — это «Night Vision, 12 марта», а не «#4f2a». Человек узнаёт ролик по
 * биту и дате, идентификатор ему не говорит ничего.
 */
export function jobTitle(job: { beatTitle: string; title: string }): string {
  return job.beatTitle.trim() || job.title.trim();
}
