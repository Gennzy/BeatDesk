/**
 * Разбор строк из формы: теги и имена.
 *
 * Это две разные вещи, и раньше они делили одну функцию, из-за чего обе
 * выходили неправильно.
 *
 * ---------------------------------------------------------------------------
 * ТЕГИ — КЛЮЧЕВЫЕ СЛОВА, И ПРОБЕЛ ИХ РАЗДЕЛЯЕТ
 *
 * Поле подписано «через пробел или запятую», и человек пишет «future, lil
 * durk», рассчитывая на три тега. Разбор резал только по запятой, и «lil
 * durk» оставалось одной записью, а телеграм потом выкидывал из неё пробел и
 * получал #lildurk. На скриншоте это и видно: вместо #future #lil #durk в
 * посте оказывалось одно слипшееся слово, которое не находит никто.
 *
 * Именно это и было первым настоящим багом: не в телеграме, а здесь.
 *
 * ---------------------------------------------------------------------------
 * ИМЕНА — НАЗВАНИЯ, И ПРОБЕЛ В НИХ ЧАСТЬ ИМЕНИ
 *
 * «Polo G», «Lil Tjay» — через пробел, и резать по нему нельзя. Имена
 * разбирает parseNames, и разбор имён больше не живёт в строке формы: он
 * повторялся в двух местах и однажды разошёлся с другим.
 */

const SEPARATORS = /[\s,]+/;

/**
 * Теги: любое разделение — и пробел, и запятая.
 *
 * Пробел внутри тега невозможен: тег без пробелов, и именно поэтому его не
 * должно быть и в разборе.
 */
export function parseTags(raw: string | null | undefined): string[] {
  const text = (raw ?? "").trim();

  if (!text) return [];

  return text.split(SEPARATORS).filter(Boolean);
}

/**
 * Имена артистов: запятая и перенос строки, пробел внутри имени сохраняется.
 *
 * Режет по запятой, а не по пробелу, иначе «Polo G» превратится в «Polo» и
 * «G» — два разных артиста, которых не существует.
 */
export function parseNames(raw: string | null | undefined): string[] {
  const text = (raw ?? "").trim();

  if (!text) return [];

  return text
    .split(/[\n,]+/)
    // Пробелы внутри имени схлопываем: «Polo   G» — это всё же «Polo G».
    .map((entry) => entry.replace(/\s+/g, " ").trim())
    .filter(Boolean);
}