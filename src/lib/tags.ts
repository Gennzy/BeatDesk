/**
 * Разбор строки тегов из формы.
 *
 * Раньше теги резались регуляркой /[\s,]+/, и «Polo G, Lil Tjay» превращался
 * в polo, g, lil, tjay — четыре бессмысленных слова вместо двух имён.
 * Тег без пробелов, а имя артиста всегда с пробелом, поэтому пробел режет
 * список, а запятая и перенос строки разделяют записи внутри одной строки.
 *
 * Разбор живёт здесь, а не в форме: его повторяют загрузка, правка и AI-
 * подсказки, и в трёх местах он разъехался сразу.
 */
export function parseTags(raw: string | null | undefined): string[] {
  const text = (raw ?? "").trim();

  if (!text) return [];

  return text
    .split(/[\n,]+/)
    // Пробелы внутри записи схлопываем, но не режем по ним.
    .map((entry) => entry.replace(/\s+/g, " ").trim())
    .filter(Boolean);
}